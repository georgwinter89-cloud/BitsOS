//! DS-4: the boot screen's pictures, made on the host at build time (the kernel has no TrueType renderer and no
//! floating point): glyph atlases of JetBrains Mono and Figtree, the title word in Bricolage Grotesque and the HUD
//! ring as a pre-rendered sprite. Everything is drawn for the 2560x1440 screen (the 1920x1080 design scaled by 4/3,
//! Georg 28.10.: "Erstmal stellen wir alles auf 2560x1440 um"). The fonts are bitscomp's (OFL 1.1, README there).
//! Without the font files the atlases come out empty and the console keeps its text screen (`bootart::ready`).
//!
//! Output in OUT_DIR: `bootart.rs` (tables, included by `src/bootart.rs`) and one `.bin` per picture.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// Design pixels to screen pixels.
const S: f32 = 4.0 / 3.0;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let fonts = manifest.join("../../user/services/bitscomp/fonts");
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    println!("cargo:rerun-if-changed=build.rs");
    let mut rs = String::from("// Generated by crates/console/build.rs (DS-4). Do not edit.\n");
    let load = |name: &str| {
        let p = fonts.join(name);
        println!("cargo:rerun-if-changed={}", p.display());
        std::fs::read(&p).ok().and_then(|b| fontdue::Font::from_bytes(b, fontdue::FontSettings::default()).ok())
    };
    let (mono, label, text, title) = (load("JetBrainsMono-400.ttf"), load("JetBrainsMono-500.ttf"), load("Figtree-400.ttf"), load("BricolageGrotesque-600.ttf"));
    let ok = mono.is_some() && label.is_some() && text.is_some() && title.is_some();
    if !ok {
        println!("cargo:warning=boot screen fonts missing in {}: the console keeps its text screen", fonts.display());
    }
    writeln!(rs, "pub const READY: bool = {ok};").unwrap();
    face(&mut rs, &out, "MONO", mono.as_ref(), 13.0 * S);
    face(&mut rs, &out, "LABEL", label.as_ref(), 11.0 * S);
    face(&mut rs, &out, "TEXT", text.as_ref(), 20.0 * S);
    word(&mut rs, &out, "TITLE", title.as_ref(), 80.0 * S, "BitsOS", -0.01);
    ring(&mut rs, &out);
    std::fs::write(out.join("bootart.rs"), rs).unwrap();
}

/// The characters of every face: printable ASCII, Latin-1 (German umlauts, ß, °, ·) and a few marks.
fn charset() -> Vec<char> {
    let mut v: Vec<char> = (0x20u32..=0x7E).chain(0xA0..=0xFF).filter_map(char::from_u32).collect();
    v.extend(['–', '…', '→']);
    v.sort_unstable();
    v
}

fn face(rs: &mut String, out: &Path, name: &str, font: Option<&fontdue::Font>, px: f32) {
    let mut bits = Vec::new();
    let mut glyphs = String::new();
    let (mut asc, mut desc) = (0, 0);
    if let Some(f) = font {
        if let Some(m) = f.horizontal_line_metrics(px) {
            asc = (m.ascent * 256.0).round() as i32;
            desc = (m.descent * 256.0).round() as i32;
        }
        for ch in charset() {
            if f.lookup_glyph_index(ch) == 0 && ch != ' ' {
                continue;
            }
            let (m, cov) = f.rasterize(ch, px);
            let top = -(m.ymin + m.height as i32);
            write!(glyphs, "Glyph {{ ch: {}, w: {}, h: {}, x: {}, y: {}, adv: {}, off: {} }},", ch as u32, m.width, m.height, m.xmin, top,
                (m.advance_width * 256.0).round() as u32, bits.len()).unwrap();
            bits.extend_from_slice(&cov);
        }
    }
    let file = format!("{}.bin", name.to_lowercase());
    std::fs::write(out.join(&file), &bits).unwrap();
    writeln!(rs, "pub static {name}: Face = Face {{ px256: {}, ascent: {asc}, descent: {desc}, glyphs: &[{glyphs}], bits: include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{file}\")) }};",
        (px * 256.0).round() as u32).unwrap();
}

/// A whole word as one coverage picture (kerning and letter spacing of the design included).
fn word(rs: &mut String, out: &Path, name: &str, font: Option<&fontdue::Font>, px: f32, text: &str, spacing_em: f32) {
    let (mut w, mut h, mut asc, mut desc) = (0usize, 0usize, 0i32, 0i32);
    let mut pic = Vec::new();
    if let Some(f) = font {
        let m = f.horizontal_line_metrics(px).unwrap();
        asc = m.ascent.round() as i32;
        desc = m.descent.round() as i32;
        let glyphs: Vec<(fontdue::Metrics, Vec<u8>, f32)> = {
            let mut pen = 0.0f32;
            let mut prev: Option<char> = None;
            let mut v = Vec::new();
            for ch in text.chars() {
                if let Some(p) = prev {
                    pen += f.horizontal_kern(p, ch, px).unwrap_or(0.0);
                }
                let (gm, cov) = f.rasterize(ch, px);
                v.push((gm, cov, pen));
                pen += gm.advance_width + spacing_em * px;
                prev = Some(ch);
            }
            v
        };
        let right = glyphs.iter().map(|(m, _, pen)| pen.round() as i32 + m.xmin + m.width as i32).max().unwrap_or(0);
        w = right.max(1) as usize;
        h = (asc - desc) as usize;
        pic = vec![0u8; w * h];
        for (m, cov, pen) in &glyphs {
            let x0 = pen.round() as i32 + m.xmin;
            let y0 = asc - (m.ymin + m.height as i32);
            for gy in 0..m.height {
                for gx in 0..m.width {
                    let (x, y) = (x0 + gx as i32, y0 + gy as i32);
                    if x >= 0 && y >= 0 && (x as usize) < w && (y as usize) < h {
                        let p = &mut pic[y as usize * w + x as usize];
                        *p = p.saturating_add(cov[gy * m.width + gx]);
                    }
                }
            }
        }
    }
    let file = format!("{}.bin", name.to_lowercase());
    std::fs::write(out.join(&file), &pic).unwrap();
    writeln!(rs, "pub static {name}: Word = Word {{ w: {w}, h: {h}, ascent: {asc}, descent: {desc}, bits: include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{file}\")) }};").unwrap();
}

// ---- the ring (the design's 520 px HUD ring of 7 circles, at rest: no spin, no pulse)

/// Sprite side and centre: the ring's 520 design pixels at 4/3, centred on a whole pixel corner.
const N: usize = 694;
const C: f32 = 347.0;

type Rgba = [f32; 4];

fn rgb(hex: u32, alpha: f32) -> Rgba {
    let c = |s: u32| ((hex >> s) & 0xFF) as f32 / 255.0 * alpha;
    [c(16), c(8), c(0), alpha]
}

/// Coverage of a circle stroke (radius `r`, width `w`, design pixels) with an optional SVG dash pattern.
fn stroke(r: f32, w: f32, dash: &[f32]) -> Vec<f32> {
    let (r, hw) = (r * S, w * S / 2.0);
    let dash: Vec<f32> = dash.iter().map(|d| d * S).collect();
    let period: f32 = dash.iter().sum();
    let mut cov = vec![0f32; N * N];
    for y in 0..N {
        for x in 0..N {
            let (dx, dy) = (x as f32 + 0.5 - C, y as f32 + 0.5 - C);
            let d = (dx * dx + dy * dy).sqrt();
            let radial = (hw + 0.5 - (d - r).abs()).clamp(0.0, 1.0);
            if radial == 0.0 {
                continue;
            }
            let along = if dash.is_empty() {
                1.0
            } else {
                // Arc length from 3 o'clock, clockwise on screen (SVG's start of a circle), at the stroke's radius.
                let mut a = dy.atan2(dx);
                if a < 0.0 {
                    a += std::f32::consts::TAU;
                }
                let s = a * r;
                let pos = s % period;
                let mut best = f32::MIN;
                for shift in [-period, 0.0, period] {
                    let mut at = shift;
                    for (i, len) in dash.iter().enumerate() {
                        if i % 2 == 0 {
                            best = best.max((pos - at).min(at + len - pos));
                        }
                        at += len;
                    }
                }
                (best + 0.5).clamp(0.0, 1.0)
            };
            cov[y * N + x] = radial * along;
        }
    }
    cov
}

fn disc(r: f32) -> Vec<f32> {
    let r = r * S;
    let mut cov = vec![0f32; N * N];
    for y in 0..N {
        for x in 0..N {
            let (dx, dy) = (x as f32 + 0.5 - C, y as f32 + 0.5 - C);
            cov[y * N + x] = (r + 0.5 - (dx * dx + dy * dy).sqrt()).clamp(0.0, 1.0);
        }
    }
    cov
}

/// An axis-aligned rectangle in design coordinates of the 520 box (box-filter coverage).
fn rect(cov: &mut [f32], x0: f32, y0: f32, x1: f32, y1: f32) {
    let map = |u: f32| C + (u - 260.0) * S;
    let (x0, x1, y0, y1) = (map(x0), map(x1), map(y0), map(y1));
    for y in 0..N {
        let oy = ((y as f32 + 1.0).min(y1) - (y as f32).max(y0)).max(0.0);
        if oy == 0.0 {
            continue;
        }
        for x in 0..N {
            let ox = ((x as f32 + 1.0).min(x1) - (x as f32).max(x0)).max(0.0);
            cov[y * N + x] = (cov[y * N + x] + ox * oy).min(1.0);
        }
    }
}

fn paint(cov: &[f32], c: Rgba) -> Vec<Rgba> {
    cov.iter().map(|&a| [c[0] * a, c[1] * a, c[2] * a, c[3] * a]).collect()
}

fn over(dst: &mut [Rgba], src: &[Rgba]) {
    for (d, s) in dst.iter_mut().zip(src) {
        let k = 1.0 - s[3];
        for i in 0..4 {
            d[i] = s[i] + d[i] * k;
        }
    }
}

/// feGaussianBlur (sigma in design pixels) as three box blurs, then merged under the sharp layer (`feMerge`).
fn glow(layer: &[Rgba], sigma: f32) -> Vec<Rgba> {
    let sigma = sigma * S;
    // Box widths for three passes (Kovesi's boxes-for-gauss).
    let wi = ((12.0 * sigma * sigma / 3.0 + 1.0).sqrt()).floor() as i32;
    let wl = if wi % 2 == 0 { wi - 1 } else { wi };
    let m = ((12.0 * sigma * sigma - 3.0 * (wl * wl) as f32 - 12.0 * wl as f32 - 9.0) / (-4.0 * wl as f32 - 4.0)).round() as i32;
    let mut b = layer.to_vec();
    for i in 0..3 {
        let r = (if i < m { wl } else { wl + 2 } - 1) / 2;
        b = box_pass(&b, r as usize, true);
        b = box_pass(&b, r as usize, false);
    }
    b
}

fn box_pass(src: &[Rgba], r: usize, horizontal: bool) -> Vec<Rgba> {
    let mut out = vec![[0f32; 4]; N * N];
    let norm = 1.0 / (2 * r + 1) as f32;
    for line in 0..N {
        let at = |i: usize| if horizontal { line * N + i } else { i * N + line };
        let mut acc = [0f32; 4];
        for i in 0..=r.min(N - 1) {
            for (k, a) in acc.iter_mut().enumerate() {
                *a += src[at(i)][k];
            }
        }
        for i in 0..N {
            for k in 0..4 {
                out[at(i)][k] = acc[k] * norm;
            }
            let add = i + r + 1;
            if add < N {
                for (k, a) in acc.iter_mut().enumerate() {
                    *a += src[at(add)][k];
                }
            }
            if i >= r {
                for (k, a) in acc.iter_mut().enumerate() {
                    *a -= src[at(i - r)][k];
                }
            }
        }
    }
    out
}

fn ring(rs: &mut String, out: &Path) {
    const ACCENT: u32 = 0x7fcfa0;
    let mut acc = vec![[0f32; 4]; N * N];
    // Outer to inner in the design's paint order.
    over(&mut acc, &paint(&stroke(246.0, 10.0, &[1.2, 8.0]), rgb(0x6b7a71, 1.0)));
    over(&mut acc, &paint(&stroke(228.0, 1.0, &[]), rgb(ACCENT, 0.25)));
    let dashed = paint(&stroke(208.0, 4.0, &[260.0, 40.0, 90.0, 40.0, 210.0, 667.0]), rgb(ACCENT, 1.0));
    over(&mut acc, &glow(&dashed, 6.0));
    over(&mut acc, &dashed);
    over(&mut acc, &paint(&stroke(180.0, 2.0, &[3.0, 7.0]), rgb(0x86afd9, 0.6)));
    over(&mut acc, &paint(&stroke(156.0, 18.0, &[330.0, 160.0]), rgb(ACCENT, 0.2)));
    over(&mut acc, &paint(&stroke(126.0, 1.4, &[]), rgb(ACCENT, 0.65)));
    let core = paint(&stroke(62.0, 12.0, &[]), rgb(0xe8eee9, 1.0));
    over(&mut acc, &glow(&core, 6.0));
    over(&mut acc, &core);
    let dot = paint(&disc(18.0), rgb(ACCENT, 1.0));
    over(&mut acc, &glow(&dot, 6.0));
    over(&mut acc, &dot);
    let mut ticks = vec![0f32; N * N];
    rect(&mut ticks, 259.0, 0.0, 261.0, 26.0);
    rect(&mut ticks, 259.0, 494.0, 261.0, 520.0);
    rect(&mut ticks, 0.0, 259.0, 26.0, 261.0);
    rect(&mut ticks, 494.0, 259.0, 520.0, 261.0);
    over(&mut acc, &paint(&ticks, rgb(ACCENT, 1.0)));
    // Spans of visible pixels per row (gaps under 8 pixels kept inside a span), premultiplied RGBA bytes.
    let q = |v: f32| (v * 255.0).round().clamp(0.0, 255.0) as u8;
    let mut bits = Vec::new();
    let mut spans = String::new();
    for y in 0..N {
        let row: Vec<[u8; 4]> = acc[y * N..(y + 1) * N].iter().map(|p| [q(p[0]), q(p[1]), q(p[2]), q(p[3])]).collect();
        let mut x = 0;
        while x < N {
            if row[x] == [0; 4] {
                x += 1;
                continue;
            }
            let start = x;
            let mut end = x;
            let mut gap = 0;
            while x < N && gap < 8 {
                if row[x] == [0; 4] {
                    gap += 1;
                } else {
                    gap = 0;
                    end = x;
                }
                x += 1;
            }
            write!(spans, "({y},{start},{},{}),", end + 1 - start, bits.len() / 4).unwrap();
            for p in &row[start..=end] {
                bits.extend_from_slice(p);
            }
        }
    }
    std::fs::write(out.join("ring.bin"), &bits).unwrap();
    writeln!(rs, "pub const RING_SIZE: u32 = {N};\npub static RING_SPANS: &[(u16, u16, u16, u32)] = &[{spans}];\npub static RING_BITS: &[u8] = include_bytes!(concat!(env!(\"OUT_DIR\"), \"/ring.bin\"));").unwrap();
}
