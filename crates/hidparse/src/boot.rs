//! Boot protocol fallback (HID 1.11 §7.2.5, Appendix B): when SET_PROTOCOL(report) is not possible
//! or the report descriptor does not parse, the driver reads boot reports with these layouts.

use crate::descriptor::ReportDescriptor;
use crate::parse::parse;

/// The boot keyboard of Appendix B.1 with the key array widened to usages 0-255, as Linux
/// usbkbd.c reads it (Japanese and other keys above 0x65 still arrive).
#[rustfmt::skip]
pub const BOOT_KEYBOARD: &[u8] = &[
    0x05, 0x01, 0x09, 0x06, 0xA1, 0x01,
    0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x08, 0x81, 0x02, // modifiers
    0x95, 0x01, 0x75, 0x08, 0x81, 0x01,                                                             // reserved byte
    0x95, 0x05, 0x75, 0x01, 0x05, 0x08, 0x19, 0x01, 0x29, 0x05, 0x91, 0x02,                         // 5 LEDs
    0x95, 0x01, 0x75, 0x03, 0x91, 0x01,
    0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x26, 0xFF, 0x00, 0x05, 0x07, 0x19, 0x00, 0x29, 0xFF, 0x81, 0x00, // 6 keys
    0xC0,
];

/// The boot mouse of Appendix B.2 with buttons 4-5 and the wheel byte that Linux usbmouse.c
/// reads; a 3-byte boot report leaves the wheel at 0.
#[rustfmt::skip]
pub const BOOT_MOUSE: &[u8] = &[
    0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x09, 0x01, 0xA1, 0x00,
    0x05, 0x09, 0x19, 0x01, 0x29, 0x05, 0x15, 0x00, 0x25, 0x01, 0x95, 0x05, 0x75, 0x01, 0x81, 0x02,
    0x95, 0x01, 0x75, 0x03, 0x81, 0x01,
    0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x09, 0x38, 0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x03, 0x81, 0x06,
    0xC0, 0xC0,
];

pub fn boot_keyboard() -> ReportDescriptor {
    parse(BOOT_KEYBOARD).unwrap_or_default()
}

pub fn boot_mouse() -> ReportDescriptor {
    parse(BOOT_MOUSE).unwrap_or_default()
}
