// Writes src/codes.rs: the Linux input codes the crate uses, with their values from
// /usr/include/linux/input-event-codes.h. Run from crates/hidparse after using a new name:
//   node tools/gen-codes.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const header = readFileSync('/usr/include/linux/input-event-codes.h', 'latin1');
const defs = new Map();
for (const m of header.matchAll(/^#define\s+((?:EV|SYN|MSC|KEY|BTN|REL|ABS|LED)_\w+)\s+(\w+)/gm)) defs.set(m[1], m[2]);
const value = (name) => {
  const v = defs.get(name);
  if (v === undefined) throw new Error(`${name} is not in input-event-codes.h`);
  return /^(0x[0-9a-f]+|\d+)$/i.test(v) ? Number(v) : value(v);
};
const files = [...readdirSync('src').filter((f) => f.endsWith('.rs') && f !== 'codes.rs').map((f) => `src/${f}`),
  ...readdirSync('tests').filter((f) => f.endsWith('.rs')).map((f) => `tests/${f}`)];
const used = new Set();
for (const f of files) for (const m of readFileSync(f, 'utf8').matchAll(/\b((?:EV|SYN|MSC|KEY|BTN|REL|ABS|LED)_[A-Z0-9_]+)\b/g)) {
  if (defs.has(m[1])) used.add(m[1]);
}
const names = [...used].sort((a, b) => value(a) - value(b) || a.localeCompare(b));
const lines = names.map((n) => `pub const ${n}: u16 = 0x${value(n).toString(16).padStart(3, '0')};`);
writeFileSync('src/codes.rs', `//! Linux input codes from /usr/include/linux/input-event-codes.h, generated by tools/gen-codes.mjs
//! (only the names this crate uses; tests/codes.rs checks them against the header).

${lines.join('\n')}

/// Every constant above by name, for the header check.
pub const ALL: &[(&str, u16)] = &[
${names.map((n) => `    ("${n}", ${n}),`).join('\n')}
];
`);
console.log(`${names.length} codes`);
