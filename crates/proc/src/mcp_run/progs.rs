//! Tiny static x86-64 Linux programs for the `run` tests (ktests here, the same bytes in
//! `host/tests/mcp/echt.mjs`): one PT_LOAD at 0x400000 holding the ELF header, the program header and the code
//! (from `nasm -f bin` with `org 0x400078`; the sources are in the comments). No libc: `write`, `nanosleep`,
//! `read`, `exit_group` as raw syscalls.

use alloc::vec::Vec;

const BASE: u64 = 0x40_0000;
const CODE_AT: u64 = 64 + 56;

/// The ELF file around `code` (entry = its first byte).
pub fn elf(code: &[u8]) -> Vec<u8> {
    let size = CODE_AT + code.len() as u64;
    let mut f = Vec::with_capacity(size as usize);
    f.extend_from_slice(b"\x7fELF\x02\x01\x01\0\0\0\0\0\0\0\0\0");
    f.extend_from_slice(&2u16.to_le_bytes()); // ET_EXEC
    f.extend_from_slice(&0x3eu16.to_le_bytes()); // x86-64
    f.extend_from_slice(&1u32.to_le_bytes());
    f.extend_from_slice(&(BASE + CODE_AT).to_le_bytes()); // entry
    f.extend_from_slice(&64u64.to_le_bytes()); // phoff
    f.extend_from_slice(&0u64.to_le_bytes()); // shoff
    f.extend_from_slice(&0u32.to_le_bytes()); // flags
    for v in [64u16, 56, 1, 64, 0, 0] {
        // ehsize, phentsize, phnum, shentsize, shnum, shstrndx
        f.extend_from_slice(&v.to_le_bytes());
    }
    f.extend_from_slice(&1u32.to_le_bytes()); // PT_LOAD
    f.extend_from_slice(&5u32.to_le_bytes()); // R + X
    for v in [0, BASE, BASE, size, size, 0x1000] {
        // offset, vaddr, paddr, filesz, memsz, align
        f.extend_from_slice(&v.to_le_bytes());
    }
    f.extend_from_slice(code);
    f
}

