export const snake = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/([A-Z])([A-Z][a-z])/g, '$1_$2').toUpperCase();

// the narrowest Rust integer type that holds every value
export function intType(values) {
  for (const v of values) if (!Number.isInteger(v)) throw new Error(`not an integer: ${v}`);
  const lo = Math.min(...values, 0), hi = Math.max(...values, 0);
  if (lo >= 0) return hi <= 0xff ? 'u8' : hi <= 0xffff ? 'u16' : hi <= 0xffffffff ? 'u32' : 'u64';
  return lo >= -0x80 && hi <= 0x7f ? 'i8' : lo >= -0x8000 && hi <= 0x7fff ? 'i16' : 'i32';
}
export const lit = (v) => (v < 0 ? String(v) : v > 9 ? hex(v) : String(v));

// `pub static NAME: &[T] = &[...];` with eight values a line
export function intSlice(name, values, doc, type = intType(values)) {
  const lines = [`/// ${doc}`, `pub static ${name}: &[${type}] = &[`];
  for (let i = 0; i < values.length; i += 8) lines.push(`    ${values.slice(i, i + 8).map(lit).join(', ')},`);
  lines.push('];');
  return lines;
}
