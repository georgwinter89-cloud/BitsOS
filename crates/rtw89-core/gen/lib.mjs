import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

// WLAN_TOOLS=<plattform/wlan> overrides, as V1's wlan-tools.mjs
export const WZ = (process.env.WLAN_TOOLS ?? '/home/georg/BitsOS/werkzeuge/plattform/wlan').replace(/\/$/, '');
export const wzUrl = (rel) => pathToFileURL(`${WZ}/${rel}`);
export const wzImport = (rel) => import(wzUrl(rel).href);
export const jsText = (file) => readFileSync(new URL(`js/${file}`, wzUrl('')), 'utf8');

// gen/phy.mjs, gen/btc.mjs: the literal after `NAME =` in a JS file, evaluated
export function constOf(file, name) {
  const text = jsText(file);
  const at = text.search(new RegExp(`\\b${name}\\s*=\\s*[\\[{]`));
  if (at < 0) throw new Error(`${name} not in ${file}`);
  let i = text.indexOf('=', at) + 1;
  while (/\s/.test(text[i])) i++;
  return evalBalanced(text, i);
}

// gen/chan-tables.mjs: the literals after `from`, in order (open: '[' or '{')
export function literals(text, from, count, open = '[') {
  let at = text.indexOf(from);
  if (at < 0) throw new Error(`not found: ${from}`);
  const out = [];
  while (out.length < count) {
    const start = text.indexOf(open, at);
    if (start < 0) throw new Error(`too few literals after ${from}`);
    const [v, end] = balanced(text, start);
    out.push(v);
    at = end + 1;
  }
  return out;
}

// gen/rfk2-tables.mjs: the first literal after the anchors, found in order
export function literalAfter(file, ...anchors) {
  const text = jsText(file);
  let at = 0;
  for (const a of anchors) {
    at = text.indexOf(a, at);
    if (at < 0) throw new Error(`${a} not in ${file}`);
    at += a.length;
  }
  return evalBalanced(text, text.slice(at).search(/[[{]/) + at);
}

function balanced(text, start) {
  let depth = 0, end = start;
  for (; end < text.length; end++) {
    if ('[{'.includes(text[end])) depth++;
    else if (']}'.includes(text[end]) && --depth === 0) break;
  }
  return [Function(`return (${text.slice(start, end + 1)});`)(), end];
}
const evalBalanced = (text, start) => balanced(text, start)[0];

