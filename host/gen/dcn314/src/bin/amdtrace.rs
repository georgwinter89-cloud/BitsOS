//! amdtrace (GX-6): names the register accesses of a Linux mmiotrace log of amdgpu.
//!
//!   amdtrace gen [--linux <linux src>] [--out <dir>] [--check]
//!       Writes one table per IP register map (`<name>\t<base_idx>\t<dword>`) from Linux's asic_reg offset headers
//!       into host/gen/dcn314/tables/ (the headers themselves never enter the tree). --linux defaults to
//!       $BITSOS_LINUX or $HOME/BitsOS/V2/ref/linux-6.6. --check writes nothing and fails if a table differs.
//!   amdtrace decode --bar5 <phys> (--bases <file> | --sysfs <dir>) [--tables <dir>] <mmiotrace log>
//!       <file>: `ip <name> <hw_id> <instance> <major.minor.rev> ... bases 0x...` lines (gx_probe's answer, or
//!       crates/drivers/amdgpu/tests/data/minipc-780m-ip.txt); <dir>: Linux's ip_discovery/die/0 sysfs tree.
//!       Prints every access inside BAR5 as `R|W width time offset NAME(IP) = value`, MM_DATA with the graphics
//!       memory address MM_INDEX/MM_INDEX_HI selected; other lines unchanged.
//!
//! A register's BAR5 dword is its IP instance's segment base (from discovery) plus the header offset (SOC15).

#![forbid(unsafe_code)]

