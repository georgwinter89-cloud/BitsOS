/// (table name, header under drivers/gpu/drm/amd/include/asic_reg). The name is the header's version, which is
/// the register map Linux's own block for that IP is built against (see `MAP`).
const HEADERS: &[(&str, &str)] = &[
    ("gc_11_0_0", "gc/gc_11_0_0_offset.h"),
    ("mp_13_0_4", "mp/mp_13_0_4_offset.h"),
    ("nbio_7_7_0", "nbio/nbio_7_7_0_offset.h"),
    ("mmhub_3_0_1", "mmhub/mmhub_3_0_1_offset.h"),
    ("osssys_6_0_0", "oss/osssys_6_0_0_offset.h"),
    ("hdp_5_2_1", "hdp/hdp_5_2_1_offset.h"),
    ("vcn_4_0_0", "vcn/vcn_4_0_0_offset.h"),
    ("lsdma_6_0_0", "lsdma/lsdma_6_0_0_offset.h"),
    ("smuio_13_0_6", "smuio/smuio_13_0_6_offset.h"),
    ("dcn_3_1_4", "dcn/dcn_3_1_4_offset.h"),
];

const ASIC_REG: &str = "drivers/gpu/drm/amd/include/asic_reg";

fn usage() -> String {
    String::from("usage: amdtrace gen [--linux DIR] [--out DIR] [--check] | amdtrace decode --bar5 PHYS (--bases FILE | --sysfs DIR) [--tables DIR] LOG")
}

/// A table's text from a header: every `reg` register with its BASE_IDX, sorted by name.
pub fn table_text(label: &str, header: &[u8]) -> Result<(String, usize), String> {
    let text = std::str::from_utf8(header).map_err(|e| format!("{label}: {e}"))?;
    // Only MMIO registers (`reg` with a 32-bit offset): PCI configuration (`cfg`), indirect (`ix`) and the 64-bit
    // offsets of other address spaces (nbio's iohub blocks) are no BAR5 addresses. Lines are blanked, not removed,
    // so parse errors keep the header's line numbers.
    let define = |l: &str| -> Option<(String, Option<u64>)> {
        let t: Vec<&str> = l.split_whitespace().collect();
        (t.len() >= 2 && t[0] == "#define").then(|| (t[1].to_string(), t.get(2).and_then(|v| hex(v).ok())))
    };
    let mut wide: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
    for l in text.lines() {
        if let Some((n, Some(v))) = define(l)
            && n.starts_with("reg")
            && !n.ends_with("_BASE_IDX")
            && v > u64::from(u32::MAX)
        {
            wide.insert(n);
        }
    }
    let other = |l: &str| match define(l) {
        None => false,
        Some((n, _)) if n.starts_with('_') => false,
        Some((n, _)) if !n.starts_with("reg") => true,
        Some((n, _)) => wide.contains(n.strip_suffix("_BASE_IDX").unwrap_or(&n)),
    };
    let skipped = text.lines().filter(|l| other(l)).count();
    let kept: String = text.lines().map(|l| if other(l) { "" } else { l }).flat_map(|l| [l, "\n"]).collect();
    let regs = parse::offsets(&kept).map_err(|e| format!("{label}: {e}"))?;
    let mut rows: Vec<(String, u32, u32)> =
        regs.iter().filter(|r| !r.indirect).filter_map(|r| Some((r.name.clone(), r.base_idx?, r.dword))).collect();
    rows.sort();
    let mut s = format!(
        "# generated by `amdtrace gen` from {label} (MIT, AMD): register name, segment index, dword offset\n# ({skipped} non-MMIO defines left out). Regenerate instead of editing.\n"
    );
    for (n, i, d) in &rows {
        let _ = writeln!(s, "{n}\t{i}\t{d:#06x}");
    }
    Ok((s, rows.len()))
}

/// $BITSOS_LINUX, else `$HOME/BitsOS/V2/ref/linux-6.6` (the desk's read-only copy; no home value in the tree).
fn default_linux() -> PathBuf {
    std::env::var_os("BITSOS_LINUX")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from(std::env::var_os("HOME").unwrap_or_default()).join("BitsOS/V2/ref/linux-6.6"))
}

fn gen_cmd(args: &[String]) -> Result<(), String> {
    let mut linux = default_linux();
    let mut out = Path::new(env!("CARGO_MANIFEST_DIR")).join("tables");
    let mut check = false;
    let mut it = args.iter();
    while let Some(a) = it.next() {
        match a.as_str() {
            "--linux" => linux = it.next().ok_or("--linux needs a path")?.into(),
            "--out" => out = it.next().ok_or("--out needs a path")?.into(),
            "--check" => check = true,
            _ => return Err(format!("unknown argument {a}")),
        }
    }
    let mut differ = Vec::new();
    for (name, rel) in HEADERS {
        let p = linux.join(ASIC_REG).join(rel);
        let bytes = std::fs::read(&p).map_err(|e| format!("{}: {e}", p.display()))?;
        let (text, n) = table_text(&format!("linux-6.6/{ASIC_REG}/{rel}"), &bytes)?;
        let dst = out.join(format!("{name}.tsv"));
        if std::fs::read(&dst).ok().as_deref() != Some(text.as_bytes()) {
            differ.push(name.to_string());
            if !check {
                std::fs::create_dir_all(&out).map_err(|e| format!("{}: {e}", out.display()))?;
                std::fs::write(&dst, text).map_err(|e| format!("{}: {e}", dst.display()))?;
            }
        }
        eprintln!("amdtrace: {name}: {n} registers");
    }
    match (check, differ.is_empty()) {
        (true, false) => Err(format!("out of date: {differ:?}")),
        (true, true) => Ok(eprintln!("amdtrace: tables up to date")),
        (false, _) => Ok(eprintln!("amdtrace: {} tables written", differ.len())),
    }
}

/// Decodes a log: accesses inside [bar5, bar5 + size) get names; MM_DATA gets its memory address.
pub fn decode(log: &str, bar5: u64, size: u64, n: &Names) -> String {
    let mut out = String::new();
    let (mut index, mut hi) = (0u32, 0u32);
    for l in log.lines() {
        let t: Vec<&str> = l.split_whitespace().collect();
        let access = matches!(t.first(), Some(&"R") | Some(&"W")) && t.len() >= 6;
        let parsed = access.then(|| Some((hex(t[4]).ok()?, hex(t[5]).ok()?))).flatten();
        let Some((phys, value)) = parsed.filter(|&(p, _)| p >= bar5 && p < bar5.saturating_add(size)) else {
            out += l;
            out.push('\n');
            continue;
        };
        let off = (phys - bar5) as u32;
        let name = n.by_dword.get(&(off / 4)).map_or_else(|| String::from("?"), |v| v.join("|"));
        let _ = write!(out, "{} {} {} {off:#07x} {name} = {value:#010x}", t[0], t[1], t[2]);
        match (t[0], off) {
            ("W", 0x0) => index = value as u32,
            ("W", 0x18) => hi = value as u32,
            (_, 0x4) => {
                let pos = u64::from(hi) << 31 | u64::from(index & 0x7FFF_FFFF);
                let _ = write!(out, "  ; vram {pos:#x}");
            }
            _ => {}
        }
        if off % 4 != 0 {
            out += "  ; unaligned";
        }
        out.push('\n');
    }
    out
}

fn decode_cmd(args: &[String]) -> Result<(), String> {
    let (mut bar5, mut bases, mut sysfs, mut log) = (None, None, None, None);
    let mut tables = Path::new(env!("CARGO_MANIFEST_DIR")).join("tables");
    let mut size = 0x80000u64;
    let mut it = args.iter();
    while let Some(a) = it.next() {
        let mut val = || it.next().cloned().ok_or(format!("{a} needs a value"));
        match a.as_str() {
            "--bar5" => bar5 = Some(hex(&val()?)?),
            "--size" => size = hex(&val()?)?,
            "--bases" => bases = Some(val()?),
            "--sysfs" => sysfs = Some(val()?),
            "--tables" => tables = val()?.into(),
            _ if log.is_none() && !a.starts_with("--") => log = Some(a.clone()),
            _ => return Err(format!("unknown argument {a}\n{}", usage())),
        }
    }
    let bar5 = bar5.ok_or("--bar5 is needed (BAR5's physical address, lspci)")?;
    let ips = match (bases, sysfs) {
        (Some(f), None) => bases_from_lines(&std::fs::read_to_string(&f).map_err(|e| format!("{f}: {e}"))?)?,
        (None, Some(d)) => bases_from_sysfs(Path::new(&d))?,
        _ => return Err(String::from("give one of --bases and --sysfs")),
    };
    let n = names(&ips, |t| {
        let p = tables.join(format!("{t}.tsv"));
        std::fs::read_to_string(&p).map_err(|e| format!("{}: {e}", p.display()))
    })?;
    let log = log.ok_or_else(usage)?;
    let text = std::fs::read_to_string(&log).map_err(|e| format!("{log}: {e}"))?;
    println!("# amdtrace: BAR5 {bar5:#x}+{size:#x}, {} IPs, {} named dwords; no table for: {}", ips.len(), n.by_dword.len(), n.unmapped.join(", "));
    print!("{}", decode(&text, bar5, size, &n));
    Ok(())
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let r = match args.first().map(String::as_str) {
        Some("gen") => gen_cmd(&args[1..]),
        Some("decode") => decode_cmd(&args[1..]),
        _ => Err(usage()),
    };
    match r {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("amdtrace: {e}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const MINI: &str = "#define _mini_OFFSET_HEADER\n\
        #define regMP0_SMN_C2PMSG_81 0x0091\n#define regMP0_SMN_C2PMSG_81_BASE_IDX 1\n\
        #define regMP1_SMN_C2PMSG_90 0x029a\n#define regMP1_SMN_C2PMSG_90_BASE_IDX 1\n\
        #define ixSOME_INDIRECT 0x0010\n";

    fn minipc() -> Vec<Ip> {
        let text = include_str!("../../../../../crates/drivers/amdgpu/tests/data/minipc-780m-ip.txt");
        bases_from_lines(text).unwrap()
    }

    #[test]
    fn table_from_a_header() {
        let (t, n) = table_text("mini", MINI.as_bytes()).unwrap();
        assert_eq!(n, 2, "indirect registers are not BAR addresses");
        assert_eq!(read_table(&t).unwrap()[0], (String::from("MP0_SMN_C2PMSG_81"), 1, 0x91));
    }

    #[test]
    fn decode_names_mp0_mp1_and_the_vram_window() {
        let ips = minipc();
        assert_eq!(ips.len(), 39);
        let (mini, _) = table_text("mini", MINI.as_bytes()).unwrap();
        let nbio = "MM_INDEX\t0\t0x0000\nMM_DATA\t0\t0x0001\nMM_INDEX_HI\t0\t0x0006\n";
        let n = names(&ips, |t| match t {
            "mp_13_0_4" => Ok(mini.clone()),
            "nbio_7_7_0" => Ok(String::from(nbio)),
            _ => Ok(String::new()),
        })
        .unwrap();
        // MP0 base[1] 0x16000 + 0x91: BAR5 0x58244 (dcn314-regs' measured MP0_C2PMSG_81).
        assert_eq!(n.by_dword.get(&(0x58244 / 4)).map(|v| v[0].as_str()), Some("MP0_SMN_C2PMSG_81"));
        let bar5 = 0xdc50_0000u64;
        let log = format!(
            "VERSION 20070824\nR 4 1.000 1 {:#x} 0x80000000 0x0 0\nW 4 1.001 1 {:#x} 0x9fff0000 0x0 0\nW 4 1.002 1 {:#x} 0x0 0x0 0\nR 4 1.003 1 {:#x} 0x28211407 0x0 0\nR 4 1.004 1 0x7c00000000 0x1 0x0 0\n",
            bar5 + 0x58244,
            bar5,
            bar5 + 0x18,
            bar5 + 0x4
        );
        let out = decode(&log, bar5, 0x80000, &n);
        let lines: Vec<&str> = out.lines().collect();
        assert_eq!(lines[0], "VERSION 20070824");
        assert_eq!(lines[1], "R 4 1.000 0x58244 MP0_SMN_C2PMSG_81 = 0x80000000");
        assert!(lines[2].starts_with("W 4 1.001 0x00000 MM_INDEX = 0x9fff0000"));
        assert_eq!(lines[4], "R 4 1.003 0x00004 MM_DATA = 0x28211407  ; vram 0x1fff0000");
        assert!(lines[5].starts_with("R 4 1.004 1 0x7c00000000"), "outside BAR5: unchanged");
        assert!(n.unmapped.iter().any(|u| u.starts_with("hw46.0")), "DF has no table: {:?}", n.unmapped);
        // MP1's register resolves against MP1's bases (equal to MP0's on the 780M).
        assert_eq!(n.by_dword.get(&(0x16000 + 0x29a)).map(|v| v[0].as_str()), Some("MP1_SMN_C2PMSG_90"));
    }

    /// The tables in the tree are what the Linux headers give (skipped without the read-only Linux tree).
    #[test]
    fn tables_up_to_date() {
        let linux = default_linux();
        if !linux.join(ASIC_REG).exists() {
            eprintln!("skip: no Linux tree at {}", linux.display());
            return;
        }
        let out = Path::new(env!("CARGO_MANIFEST_DIR")).join("tables");
        for (name, rel) in HEADERS {
            let (text, _) = table_text(&format!("linux-6.6/{ASIC_REG}/{rel}"), &std::fs::read(linux.join(ASIC_REG).join(rel)).unwrap()).unwrap();
            assert_eq!(std::fs::read_to_string(out.join(format!("{name}.tsv"))).ok(), Some(text), "{name}: run amdtrace gen");
        }
    }
}
