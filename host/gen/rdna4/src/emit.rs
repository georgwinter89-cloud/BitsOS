//! Renders one Rust file per block: a `Reg` constant per MMIO register, `ix`/`cfg` constants in their own modules, the
//! fields in `f` (`REGISTER__FIELD`, as Linux names them without the SHIFT/MASK halves), and `REGS` for lookups by name.

use crate::parse::{Kind, RawReg};
use std::fmt::Write;

pub struct Block {
    /// The header stem and the module's name, e.g. `gc_12_0_0`.
    pub name: &'static str,
    /// The folder below `include/asic_reg`.
    pub dir: &'static str,
    /// Registers the header gives no `_BASE_IDX` (left out; `parse::offsets`).
    pub headerless: &'static [&'static str],
    /// Registers whose masks are 64 bits wide (their fields are left out; `parse::fields`).
    pub wide: &'static [&'static str],
    /// Defines of the offset header that are skipped whole (a `_BASE_IDX` whose register the header lacks).
    pub stray: &'static [&'static str],
}

