pub struct Counts {
    pub mmio: usize,
    pub indirect: usize,
    pub config: usize,
    pub fields: usize,
}

fn ident(name: &str) -> Result<&str, String> {
    let ok = name.chars().next().is_some_and(|c| c.is_ascii_alphabetic() || c == '_') && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
    if ok { Ok(name) } else { Err(format!("{name:?} is no Rust identifier")) }
}

pub fn block(b: &Block, regs: &[RawReg], orphans: usize, halves: &[String]) -> Result<(String, Counts), String> {
    let of = |k: Kind| regs.iter().filter(move |r| r.kind == k);
    let c = Counts { mmio: of(Kind::Mmio).count(), indirect: of(Kind::Indirect).count(), config: of(Kind::Config).count(), fields: regs.iter().map(|r| r.fields.len()).sum() };
    let mut s = String::new();
    let _ = writeln!(s, "// @generated by host/gen/rdna4 from linux-7.3.1 drivers/gpu/drm/amd/include/asic_reg/{}/{}_offset.h and _sh_mask.h", b.dir, b.name);
    let _ = writeln!(s, "// (MIT, AMD). Regenerate instead of editing. {} registers, {} indirect, {} configuration-space, {} fields;", c.mmio, c.indirect, c.config, c.fields);
    let _ = writeln!(s, "// {orphans} mask defines name no register of the offset header and are left out; so are the registers the header");
    let _ = writeln!(s, "// gives no BASE_IDX: {:?}, the fields of its 64-bit registers: {:?}, and stray defines: {:?}.", b.headerless, b.wide, b.stray);
    let _ = writeln!(s, "// Fields the mask header defines by half (left out): {halves:?}.");
    let mut uses = vec!["Field", "Reg"];
    if c.config > 0 {
        uses.insert(0, "Cfg");
    }
    if c.indirect > 0 {
        uses.insert(uses.len() - 1, "Ix");
    }
    let _ = writeln!(s, "use crate::{{{}}};\n", uses.join(", "));
    let _ = writeln!(s, "pub const NAME: &str = \"{}\";\n", b.name);
    for r in of(Kind::Mmio) {
        let n = ident(&r.name)?;
        let _ = writeln!(s, "pub const {n}: Reg = Reg::new(\"{n}\", {}, {:#06x});", r.base_idx.unwrap_or(0), r.offset);
    }
    let _ = writeln!(s, "\n/// Every MMIO register of the block, in header order.\npub static REGS: [Reg; {}] = [", c.mmio);
    for chunk in of(Kind::Mmio).collect::<Vec<_>>().chunks(4) {
        let _ = writeln!(s, "    {},", chunk.iter().map(|r| r.name.as_str()).collect::<Vec<_>>().join(", "));
    }
    s += "];\n";
    for (kind, module, ty) in [(Kind::Indirect, "ix", "Ix"), (Kind::Config, "cfg", "Cfg")] {
        if of(kind).next().is_none() {
            continue;
        }
        let _ = writeln!(s, "\npub mod {module} {{\n    use super::{ty};");
        for r in of(kind) {
            let n = ident(&r.name)?;
            let _ = writeln!(s, "    pub const {n}: {ty} = {ty}::new(\"{n}\", {:#06x});", r.offset);
        }
        s += "}\n";
    }
    s += "\n/// Bit fields, `REGISTER__FIELD`.\npub mod f {\n    use super::Field;\n";
    for r in regs {
        for f in &r.fields {
            let _ = writeln!(s, "    pub const {}__{}: Field = Field::new({}, {:#010x});", ident(&r.name)?, ident(&f.name)?, f.shift, f.mask);
        }
    }
    s += "}\n";
    Ok((s, c))
}

pub fn index(names: &[&str]) -> String {
    let mut s = String::from("// @generated by host/gen/rdna4. Regenerate instead of editing.\n");
    for n in names {
        let _ = writeln!(s, "pub mod {n};");
    }
    s += "\n/// (block name, its MMIO registers) for lookups by name.\npub static BLOCKS: &[(&str, &[crate::Reg])] = &[\n";
    for n in names {
        let _ = writeln!(s, "    ({n}::NAME, &{n}::REGS),");
    }
    s += "];\n";
    s
}
