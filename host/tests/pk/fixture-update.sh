#!/bin/bash
# PK-6e: adds the update states to a fixture mirror that fixture-mirror.sh built in OUT (never in git: third-party
# packages). The real packagers' keys never sign anything here: three TEST keys (Ed25519, made by the build host's
# gpg in a scratch home OUT/upd/gnupg, which is removed at the end) sign the rebuilt and the made-up packages.
#   OUT/upd/keys/      bitstest.gpg (test key A) and bitstest-trusted (A): the TEST keyring a scenario copies beside
#                      the real keyrings of /usr/share/pacman/keyrings (populate's three files, pacman-key.sh.in:283)
#   OUT/upd/b/fixture/ the packages of main/fixture, but oniguruma rebuilt as <version>.1 (the same files, a new
#                      .PKGINFO and .MTREE as makepkg makes them) and signed by test key B, which only the keyring
#                      package brings; bitstest-keyring 1-1 (keys A and B, both trusted) signed by A;
#                      bitstest-mirrorlist 1-1 (etc/pacman.d/bitstest-mirrorlist: Server = MIRROR/upd/b/$repo)
#                      signed by A; fixture.db by repo-add, newer than main's
#   OUT/upd/c/fixture/ b's packages, but bitstest-keyring 2-1 signed by test key C, which no keyring knows: refused
# Usage: fixture-update.sh OUT [MIRROR] (MIRROR: the URL the guest or the fetch stand-in reaches OUT at).
# Runs as a user (never root), writes only below OUT.
set -eu -o pipefail
OUT="${1:?usage: fixture-update.sh OUT [MIRROR]}"
MIRROR="${2:-http://fix}"
mkdir -p "$OUT"
OUT="$(realpath "$OUT")"
[ "$(id -u)" != 0 ] || { echo "RED: fixture-update.sh runs as a user, not as root"; exit 1; }
for t in repo-add bsdtar gpg gpgconf zstd gzip python3; do command -v $t >/dev/null || { echo "RED: $t missing on this host"; exit 1; }; done
[ -f "$OUT/main/fixture/fixture.db" ] || { echo "RED: $OUT/main/fixture is not a fixture mirror (run fixture-mirror.sh first)"; exit 1; }
U="$OUT/upd"
rm -rf "$U"
mkdir -p "$U/keys" "$U/b/fixture" "$U/c/fixture" "$U/work"
# A short home: gpg's agent socket lives below it (or below /run/user when the path is long).
G="$(mktemp -d "${TMPDIR:-/tmp}/bitstest-gnupg.XXXXXX")"
trap 'gpgconf --homedir "$G" --kill all >/dev/null 2>&1 || true; rm -rf "$G"' EXIT
NOW=$(date +%s)
T=$((NOW - 3600))
# Keys and signatures dated a day back, so a guest clock a little behind the host's never sees them in the future.
KT=$((NOW - 86400))
gg() { LC_ALL=C gpg --homedir "$G" --batch --quiet --no-tty --pinentry-mode loopback --passphrase '' --faked-system-time "$KT!" "$@" 2> >(grep -v "faked system time" >&2); }
fpr() { gg --with-colons --list-keys "$1" | awk -F: '/^fpr:/ { print $10; exit }'; }
for k in A B C; do gg --quick-gen-key "BitsOS Test key $k <$k@bitsos.test>" ed25519 sign never 2>/dev/null; done
FA="$(fpr A@bitsos.test)" FB="$(fpr B@bitsos.test)" FC="$(fpr C@bitsos.test)"
[ -n "$FA" ] && [ -n "$FB" ] && [ -n "$FC" ] || { echo "RED: gpg made no test keys"; exit 1; }
gg --export "$FA" > "$U/keys/bitstest.gpg"
printf '%s:4:\n' "$FA" > "$U/keys/bitstest-trusted"
sign() { gg --local-user "$1" --detach-sign --output "$2.sig" "$2"; }

# makepkg's packaging (scripts/makepkg.sh.in:617 .MTREE, :625 the package), as root's files (fakeroot's view).
pack() {
    local dir="$1" out="$2"
    # list_package_files (makepkg.sh.in:562): every path, dot files too, in C order.
    files() { find . -mindepth 1 ! -name .MTREE -printf '%P\0' | LC_ALL=C sort -z; }
    (cd "$dir" && find . -exec touch -h -d @"$T" {} + \
        && files | LC_ALL=C bsdtar -cnf - --format=mtree --uid 0 --gid 0 --uname root --gname root \
            --options='!all,use-set,type,uid,gid,mode,time,size,sha256,link' --null --files-from - | gzip -c -f -n > .MTREE \
        && touch -d @"$T" .MTREE \
        && { printf '.MTREE\0'; files; } | LC_ALL=C bsdtar --no-fflags -cnf - --uid 0 --gid 0 --uname root --gname root --null --files-from - \
            | zstd -q -c -T0 > "$out")
}

# A data package: NAME VERSION TREE (its files at their paths) OUT-DIR
datapkg() {
    local name="$1" ver="$2" tree="$3" dst="$4" w="$U/work/$1-$2"
    rm -rf "$w"
    cp -r "$tree" "$w"
    cat > "$w/.PKGINFO" <<EOF
# Generated by fixture-update.sh (PK-6e test package)
pkgname = $name
pkgbase = $name
pkgver = $ver
pkgdesc = BitsOS PK-6e test data package
url = https://bitsos.test
builddate = $T
packager = BitsOS Test <test@bitsos.test>
size = $(du -sb "$tree" | cut -f1)
arch = any
license = MIT
EOF
    pack "$w" "$dst/$name-$ver-any.pkg.tar.zst"
}

# b: main's packages, oniguruma rebuilt.
for f in "$OUT/main/fixture/"*.pkg.tar.zst; do
    case "${f##*/}" in oniguruma-*) continue;; esac
    cp "$f" "$f.sig" "$U/b/fixture/"
done
onig="$(cd "$OUT/main/fixture" && ls oniguruma-*.pkg.tar.zst | head -1)"
w="$U/work/oniguruma"
mkdir -p "$w"
bsdtar -xpf "$OUT/main/fixture/$onig" -C "$w"
old="$(sed -n 's/^pkgver = //p' "$w/.PKGINFO")"
arch="$(sed -n 's/^arch = //p' "$w/.PKGINFO")"
new="$old.1"
sed -i "s/^pkgver = .*/pkgver = $new/; s/^builddate = .*/builddate = $T/" "$w/.PKGINFO"
rm -f "$w/.MTREE"
newf="oniguruma-$new-$arch.pkg.tar.zst"
pack "$w" "$U/b/fixture/$newf"
sign "$FB" "$U/b/fixture/$newf"
# The keyring package: A and B, both trusted.
K="usr/share/pacman/keyrings"
mkdir -p "$U/work/kr1/$K" "$U/work/ml/etc/pacman.d" "$U/work/kr2/$K"
gg --export "$FA" "$FB" > "$U/work/kr1/$K/bitstest.gpg"
printf '%s:4:\n%s:4:\n' "$FA" "$FB" > "$U/work/kr1/$K/bitstest-trusted"
datapkg bitstest-keyring 1-1 "$U/work/kr1" "$U/b/fixture"
sign "$FA" "$U/b/fixture/bitstest-keyring-1-1-any.pkg.tar.zst"
printf '# PK-6e test mirror list\nServer = %s/upd/b/$repo\n' "$MIRROR" > "$U/work/ml/etc/pacman.d/bitstest-mirrorlist"
datapkg bitstest-mirrorlist 1-1 "$U/work/ml" "$U/b/fixture"
sign "$FA" "$U/b/fixture/bitstest-mirrorlist-1-1-any.pkg.tar.zst"
(cd "$U/b/fixture" && repo-add -q fixture.db.tar.gz ./*.pkg.tar.zst > /dev/null)
rm -f "$U/b/fixture/fixture.db" "$U/b/fixture/fixture.files"
cp "$U/b/fixture/fixture.db.tar.gz" "$U/b/fixture/fixture.db"

# c: b, with a newer keyring package signed by C (unknown to every keyring).
for f in "$U/b/fixture/"*.pkg.tar.zst; do
    case "${f##*/}" in bitstest-keyring-*) continue;; esac
    cp "$f" "$f.sig" "$U/c/fixture/"
done
T=$((T + 60))
gg --export "$FA" "$FB" "$FC" > "$U/work/kr2/$K/bitstest.gpg"
printf '%s:4:\n%s:4:\n%s:4:\n' "$FA" "$FB" "$FC" > "$U/work/kr2/$K/bitstest-trusted"
datapkg bitstest-keyring 2-1 "$U/work/kr2" "$U/c/fixture"
sign "$FC" "$U/c/fixture/bitstest-keyring-2-1-any.pkg.tar.zst"
(cd "$U/c/fixture" && repo-add -q fixture.db.tar.gz ./*.pkg.tar.zst > /dev/null)
rm -f "$U/c/fixture/fixture.db" "$U/c/fixture/fixture.files"
cp "$U/c/fixture/fixture.db.tar.gz" "$U/c/fixture/fixture.db"
rm -rf "$U/work"
echo "fixture update states in $U: b (oniguruma $old -> $new signed by test key B ${FB:0:16}, bitstest-keyring 1-1 and bitstest-mirrorlist 1-1 signed by A ${FA:0:16}), c (bitstest-keyring 2-1 signed by the unknown C ${FC:0:16})"
