//! A package's metadata members: `.PKGINFO` (`key = value` lines, written by makepkg's write_pkginfo:
//! pacman/scripts/makepkg.sh.in, keys in pacman/doc/PKGBUILD.5 and libmakepkg), `.BUILDINFO` (BUILDINFO.5) and
//! `.INSTALL`. They are kept in `/apps/.pkgs/<pkg>/<ver>/.meta/` as information; `.INSTALL` is never run (plan
//! 1.7: it could change anything outside the package, B2): its functions and the known patterns in them go into
//! the install report (pacman would run them through trans.c:337 _alpm_runscriptlet).

/// Each metadata member is read whole; real ones are a few KiB (BUILDINFO with its installed list: tens of KiB).
pub const META_MAX: u64 = 1 << 20;

pub const PKGINFO: &str = ".PKGINFO";
pub const BUILDINFO: &str = ".BUILDINFO";
pub const INSTALL: &str = ".INSTALL";
pub const MTREE: &str = ".MTREE";
/// The metadata members a package may carry at its top; any other top-level dot file is an ordinary file.
pub const MEMBERS: [&str; 5] = [PKGINFO, BUILDINFO, INSTALL, MTREE, ".CHANGELOG"];

#[derive(Debug, Default, Clone, PartialEq)]
pub struct PkgInfo {
    pub name: String,
    pub version: String,
    pub packager: String,
    pub arch: String,
}

pub fn pkginfo(text: &str) -> PkgInfo {
    let mut p = PkgInfo::default();
    for l in text.lines() {
        let Some((k, v)) = l.split_once(" = ") else { continue };
        let v = v.trim().to_string();
        match k.trim() {
            "pkgname" => p.name = v,
            "pkgver" => p.version = v,
            "packager" => p.packager = v,
            "arch" => p.arch = v,
            _ => {}
        }
    }
    p
}

/// The scriptlet functions pacman knows (trans.c:337, PKGBUILD.5 "install").
pub const FUNCTIONS: [&str; 6] = ["pre_install", "post_install", "pre_upgrade", "post_upgrade", "pre_remove", "post_remove"];

/// What `.INSTALL` would do, by pattern, in German for the report (plan 1.7).
pub const PATTERNS: [(&str, &str); 12] = [
    ("systemd-sysusers", "legt Systembenutzer an (systemd-sysusers)"),
    ("useradd", "legt einen Systembenutzer an (useradd)"),
    ("groupadd", "legt eine Systemgruppe an (groupadd)"),
    ("getent group", "fragt Systemgruppen ab (getent group)"),
    ("getent passwd", "fragt Systembenutzer ab (getent passwd)"),
    ("setcap", "setzt Datei-Fähigkeiten (setcap)"),
    ("chown", "ändert Besitzer (chown)"),
    ("systemctl", "steuert Systemdienste (systemctl)"),
    ("fc-cache", "baut den Schriften-Cache (fc-cache)"),
    ("update-", "ruft ein update-…-Werkzeug auf"),
    ("ldconfig", "ruft ldconfig auf"),
    ("etc/shells", "trägt sich in /etc/shells ein"),
];

#[derive(Debug, Default, Clone, PartialEq)]
pub struct Scriptlet {
    pub functions: Vec<String>,
    pub patterns: Vec<&'static str>,
    /// Creates a system user or group (plan 1.7: installed anyway, the files run as the program's own uid).
    pub users: bool,
}

pub fn scriptlet(text: &str) -> Scriptlet {
    let mut s = Scriptlet::default();
    for f in FUNCTIONS {
        if text.lines().any(|l| {
            let t = l.trim_start();
            t.starts_with(f) && t[f.len()..].trim_start().starts_with("()")
        }) {
            s.functions.push(f.to_string());
        }
    }
    for (pat, de) in PATTERNS {
        if text.contains(pat) {
            s.patterns.push(de);
        }
    }
    s.users = ["systemd-sysusers", "useradd", "groupadd"].iter().any(|p| text.contains(p));
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reads_pkginfo_and_scriptlets() {
        let p = pkginfo("# Generated by makepkg 7.1.0\npkgname = jq\npkgver = 1.8.2-1.1\npackager = CachyOS <admin@cachyos.org>\narch = x86_64_v3\n");
        assert_eq!((p.name.as_str(), p.version.as_str(), p.arch.as_str()), ("jq", "1.8.2-1.1", "x86_64_v3"));
        let s = scriptlet("post_upgrade() {\n  /usr/bin/fc-cache -rs\n}\n\npost_install() {\n  post_upgrade $1 0\n}\n");
        assert_eq!(s.functions, ["post_install", "post_upgrade"]);
        assert!(s.patterns.iter().any(|p| p.contains("fc-cache")) && !s.users);
        assert!(scriptlet("post_install() {\n systemd-sysusers foo.conf\n}\n").users);
    }
}
