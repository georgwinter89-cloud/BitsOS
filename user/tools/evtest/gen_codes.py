#!/usr/bin/env python3
"""Writes src/codes.rs (event type and code names) from Linux's input-event-codes.h.

Usage: python3 -I gen_codes.py <linux>/include/uapi/linux/input-event-codes.h > src/codes.rs
The first name of a value wins (as evtest's tables); aliases defined by name, range markers, *_MAX and *_CNT are skipped."""
import re, sys

GROUPS = [("EV", "EV"), ("SYN", "SYN"), ("KEY", "KEY"), ("BTN", "KEY"), ("REL", "REL"), ("ABS", "ABS"),
          ("MSC", "MSC"), ("SW", "SW"), ("LED", "LED"), ("SND", "SND"), ("REP", "REP"), ("INPUT_PROP", "PROP")]
# Range markers that share a value with a real button (evtest names the button).
MARKERS = {"BTN_MISC", "BTN_MOUSE", "BTN_JOYSTICK", "BTN_GAMEPAD", "BTN_DIGI", "BTN_WHEEL", "BTN_TRIGGER_HAPPY"}
tables = {t: {} for _, t in GROUPS}
for line in open(sys.argv[1]):
    m = re.match(r"#define\s+([A-Z][A-Z0-9_]*)\s+(0x[0-9a-fA-F]+|\d+)\b", line)
    if not m:
        continue
    name, val = m.group(1), int(m.group(2), 0)
    if name.endswith("_MAX") or name.endswith("_CNT") or name in MARKERS:
        continue
    for prefix, table in sorted(GROUPS, key=lambda g: -len(g[0])):
        if name.startswith(prefix + "_"):
            tables[table].setdefault(val, name)
            break
print("// Generated by gen_codes.py from linux-6.6/include/uapi/linux/input-event-codes.h; do not edit.")
for t, vals in tables.items():
    print(f"pub const {t}: &[(u16, &str)] = &[")
    for v in sorted(vals):
        print(f"    ({v:#x}, \"{vals[v]}\"),")
    print("];")
